// The public pls,fix: the open-source build served as plain files from the public repo's GitHub
// Pages, with no relay (src/link/local-only.ts). Owns its web address and its own add-in identity,
// so it installs beside the hosted add-in instead of replacing it. Invariant: nothing in the public
// manifest names the hosted server; every URL is under PUBLIC_BASE_URL.

import type { AddinSpec, ManifestEnvironment } from "./spec";

export const PUBLIC_ORIGIN = "https://skill-issue-hq-dev.github.io";
export const PUBLIC_BASE_URL = `${PUBLIC_ORIGIN}/plsfix/`;
// Its own GUID: Office tells add-ins apart by Id, and the hosted one keeps FF1B34D8-...
export const PUBLIC_ID = "F516A2FC-E2D6-4920-92C8-DB1A3677DBFA";

export const PUBLIC_ENVIRONMENT: ManifestEnvironment = {
  name: "public",
  file: "manifest.public.xml",
  baseUrl: PUBLIC_BASE_URL,
  comment:
    "Public manifest: the open-source pls,fix served from GitHub Pages, with its own GUID so it\n" +
    `     installs beside the hosted add-in. Every link stays on the user's PC (no relay).\n` +
    "     GENERATED by scripts/build-manifests.ts from manifest/spec.ts + manifest/public.ts - do not edit by hand.",
};

export function publicAddin(addin: AddinSpec): AddinSpec {
  return {
    ...addin,
    id: PUBLIC_ID,
    supportUrl: `${PUBLIC_BASE_URL}support.html`,
    appDomain: PUBLIC_ORIGIN,
  };
}
